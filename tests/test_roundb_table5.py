    def test_lost_positive_masks_and_all_three_denominators(self):
        common, galleries, _ = s11.common_query_sets(self.ann)
        queries = common["A"]
        absent_id = int(self.ann.query_ids[queries[0]])
        same = galleries[0][self.ann.gallery_ids[galleries[0]] != absent_id]
        detail, delta, valid = target.pair_outcomes(self.sim, self.ann, queries, same, galleries[1])
        lost = self.ann.query_ids[queries] == absent_id
        self.assertEqual(detail["same"]["zero_positive_queries"], int(lost.sum()))
        self.assertEqual(detail["same"]["zero_positive_identities"], 1)
        np.testing.assert_array_equal(valid, ~lost)
        draws = [dict(seed=2026, detail=detail, difference=delta, valid=valid)]
        a = target.policy_summary(draws, self.ann.query_ids[queries], "a_fixed_misses", 100, 2026)
        b = target.policy_summary(draws, self.ann.query_ids[queries], "b_common_valid_queries", 100, 2026)
        self.assertEqual(a["per_draw"][0]["denominator"], len(queries))
        self.assertEqual(b["per_draw"][0]["denominator"], int((~lost).sum()))
        rng = np.random.default_rng(2026)
        preserving_same = target.at_least_two_gallery(self.ann, queries, galleries[0], len(galleries[0]), rng, True)
        preserving_cross = target.at_least_two_gallery(self.ann, queries, galleries[1], len(galleries[1]), rng, False)
        cdetail, cdelta, cvalid = target.pair_outcomes(self.sim, self.ann, queries, preserving_same, preserving_cross)
        c = target.policy_summary([dict(seed=2026, detail=cdetail, difference=cdelta, valid=cvalid)],
                                  self.ann.query_ids[queries], "c_at_least_two_positives", 100, 2026)
        self.assertEqual(c["per_draw"][0]["denominator"], len(queries))
        self.assertTrue(cvalid.all())
        print(f"ROUND B TABLE5 MOCK zero-positive branch: lost queries={int(lost.sum())}; lost IDs=1; "
              f"a/b/c denominators={len(queries)}/{int((~lost).sum())}/{len(queries)}")

