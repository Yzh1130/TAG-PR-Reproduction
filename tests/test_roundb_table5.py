    def test_identity_bootstrap_repeats_all_queries_not_identity_means(self):
        labels = np.array([4, 4, 9])
        delta = np.array([[1.0, 0.0, -1.0], [1.0, 1.0, -1.0]])
        got = target.identity_interval(delta, np.ones_like(delta, bool), labels, repeats=100, seed=7)
        rng = np.random.default_rng(7)
        draw = rng.integers(0, 2, (100, 2))
        numerator = np.array([1.5, -1.0])[draw].sum(1)
        denominator = np.array([2.0, 1.0])[draw].sum(1)
        expected = numerator * 100 / denominator
        np.testing.assert_array_equal(got["ci95_percentile_pp"], np.percentile(expected, [2.5, 97.5]))
        self.assertEqual(got["bootstrap_mean_delta_pp"], expected.mean())
        first = target.identity_interval(delta, np.ones_like(delta, bool), labels, 100, 7, True)
        second = target.identity_interval(delta, np.ones_like(delta, bool), labels, 100, 7, True)
        self.assertEqual(first, second)

    def test_masked_draw_mean_and_undefined_bootstrap_are_explicit(self):
        delta = np.array([[1.0, 0, -1.0], [0.0, 1.0, -1.0]])
        mask = np.array([[True, False, True], [True, True, False]])
        got = target.identity_interval(delta, mask, np.array([0, 1, 2]), 100, 2026)
        means = np.array([0.5, 1.0, -1.0])
        self.assertEqual(got["observed_delta_pp"], means.mean()*100)
        zero = target.identity_interval(delta, np.zeros_like(mask), np.array([0, 1, 2]), 100, 2026, True)
        self.assertEqual(zero["undefined_replicates"], 100)
        self.assertIsNone(zero["ci95_percentile_pp"])

    def test_cli_help_and_exclusive_output_and_provenance(self):
        help_result = subprocess.run([sys.executable, "scripts/R1_table5_clusters.py", "--help"],
                                     capture_output=True, text=True)
        self.assertEqual(help_result.returncode, 0, help_result.stderr)
        with tempfile.TemporaryDirectory(prefix="roundb_table5_200x100_mock_") as directory:
            root = Path(directory)
            data = root / "inputs"
            data.mkdir()
            paths = [data / "sim.npy", data / "ann.json", data / "S11.json"]
            np.save(paths[0], self.sim)
            for path, value in zip(paths[1:], (self.records, self.authority)):
                path.write_text(json.dumps(value), encoding="utf-8")
            before = [hashlib.sha256(p.read_bytes()).hexdigest() for p in paths]
            out = root / "outputs" / "table5.json"
            command = ["--sim", str(paths[0]), "--anno", str(paths[1]), "--s11-json", str(paths[2]),
                       "--out", str(out), "--bootstrap", "100"]
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(target.main(command), 0)
            initial = out.read_bytes()
            report = json.loads(initial)
            self.assertEqual(report["status"], "complete")
            self.assertEqual(len(report["provenance"]["git_HEAD"]), 40)
            self.assertEqual(len(report["provenance"]["inputs"]), 3)
            for item in report["provenance"]["inputs"].values():
                self.assertEqual(len(item["sha256_16"]), 16)
                self.assertGreater(item["bytes"], 0)
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(target.main(command), 0)
            self.assertEqual(out.read_bytes(), initial)
            self.assertEqual(len(list(out.parent.glob("*.json"))), 2)
            self.assertEqual(before, [hashlib.sha256(p.read_bytes()).hexdigest() for p in paths])
            bad = copy.deepcopy(self.authority)
            bad["A"]["original"]["A->A"]["R1"] += 1
            paths[2].write_text(json.dumps(bad), encoding="utf-8")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(target.main(command), 2)
            reports = [json.loads(p.read_text()) for p in out.parent.glob("*.json")]
            self.assertEqual(sum(r["status"] == "stopped" for r in reports), 1)
            print("ROUND B TABLE5 MOCK CLI: --help PASS; three hashed inputs; exact-reference fail STOP; collision preserves first JSON/log")


