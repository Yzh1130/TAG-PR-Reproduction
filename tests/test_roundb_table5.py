def mock_fixture(records=None):
    original_records, _, sim, _ = mock_data()
    records = original_records if records is None else records
    ann = annotation_from_records(records)
    with contextlib.redirect_stdout(io.StringIO()):
        control = s11.run_controlled(sim, ann, "common-min", bootstrap=2)
    authority = json_ready(dict(A=control, seeds=dict(gallery=list(range(2026, 2036)))))
    return records, ann, sim, authority


class Table5Tests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.records, cls.ann, cls.sim, cls.authority = mock_fixture()

    def analyze(self, authority=None, repeats=100):
        with contextlib.redirect_stdout(io.StringIO()):
            return target.analyze(self.sim, self.ann, authority or self.authority, bootstrap=repeats)

    def test_mock_all_policies_and_all_reference_gates(self):
        report = self.analyze(repeats=10000)
        self.assertEqual(report["status"], "complete")
        self.assertEqual(self.sim.shape, (200, 100))
        self.assertTrue(all(check["passed"] for check in report["checks"]))
        union = set()
        for name, row in report["groups"].items():
            union.update(row["identity_ids"])
            self.assertEqual(sum(row["query_counts_by_identity"].values()), row["n_queries"])
            self.assertEqual(row["n_identities"], len(row["identity_ids"]))
            self.assertEqual(len(row["authoritative_trials"]), 10)
            for draw in row["authoritative_trials"]:
                for side in ("same", "cross"):
                    self.assertEqual(draw[side]["zero_positive_queries"], 0)
                    self.assertEqual(draw[side]["zero_positive_identities"], 0)
            policies = row["zero_positive_policies"]
            self.assertEqual(len(policies), 3)
            for key, item in policies.items():
                self.assertEqual(item["status"], "complete")
                self.assertEqual(len(item["per_draw"]), 10)
                self.assertEqual(item["identity_bootstrap_conditional_on_fixed_draws"]["unit"], "identity")
                self.assertEqual(item["two_stage_identity_and_gallery_bootstrap"]["unit"], "identity_and_gallery_draw")
                self.assertEqual(item["identity_bootstrap_conditional_on_fixed_draws"]["repeats"], 10000)
            self.assertEqual(policies["a_fixed_misses"], policies["b_common_valid_queries"] |
                             {"per_query_average_policy": policies["a_fixed_misses"]["per_query_average_policy"]})
            print(f"ROUND B TABLE5 MOCK side={name}; queries={row['n_queries']}; IDs={row['n_identities']}; "
                  f"all 3 policies emitted; fixed-draw CI="
                  f"{policies['a_fixed_misses']['identity_bootstrap_conditional_on_fixed_draws']['ci95_percentile_pp']}; "
                  f"two-stage CI={policies['a_fixed_misses']['two_stage_identity_and_gallery_bootstrap']['ci95_percentile_pp']}")
        self.assertEqual(report["n_unique_identity_union"], len(union))
        self.assertEqual(report["unique_identity_union"], sorted(union))
        self.assertIn("skips no-positive", report["zero_positive_original_policy"]["evaluator"])
        print(f"ROUND B TABLE5 MOCK shape=200x100; exact S11 checks={len(report['checks'])}; "
              "all positive-preserving S11 draw lost-positive counts=0")

    def test_saved_indices_priority_and_no_index_same_seed_replay(self):
        expected = self.analyze()
        no_indices = copy.deepcopy(self.authority)
        for control in no_indices["A"]["gallery_control"].values():
            for draw in control["trials"]:
                draw.pop("same_gallery_indices")
                draw.pop("cross_gallery_indices")
        actual = self.analyze(no_indices)
        for name in ("A", "G"):
            self.assertEqual(expected["groups"][name]["zero_positive_policies"], actual["groups"][name]["zero_positive_policies"])
            for left, right in zip(expected["groups"][name]["authoritative_trials"], actual["groups"][name]["authoritative_trials"]):
                for key in ("same", "cross"):
                    self.assertEqual(left[key], right[key])
                    self.assertEqual(left["index_source"][key], "saved_indices")
                    self.assertEqual(right["index_source"][key], "same_seed_same_S11_code_replay")

